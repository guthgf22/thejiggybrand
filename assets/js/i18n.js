const KEY = 'jiggy.lang';

// The language picked last (on any page of the site); `lang` below is the one this page was drawn in.
export function savedLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'tr') return saved;
  } catch (e) { /* storage blocked */ }
  return 'tr'; // Turkish first; English is one tap away in the header and menu.
}

export const lang = savedLang();
document.documentElement.lang = lang;

export function setLang(next) {
  try { localStorage.setItem(KEY, next); } catch (e) { /* storage blocked */ }
}

export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

// Picks the right language from a {en, tr} object.
export function L(obj) {
  if (obj == null) return '';
  return obj[lang] ?? obj.en;
}

export const currency = CONFIG.currency[lang];
const priceKey = currency === 'TRY' ? 'try' : 'usd';
const nf = new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US', {
  style: 'currency',
  currency,
  maximumFractionDigits: 0,
});

// amount can be a {usd, try} object or a plain number already in the active currency.
export function amountOf(price) {
  return typeof price === 'number' ? price : price[priceKey];
}

export function money(price) {
  return nf.format(amountOf(price));
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    });
  });
}
